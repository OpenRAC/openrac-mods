"""Writes src/classes.h, the difficulty mod's table of moby classes, from classes.tsv.

    python3 tools/gen_classes.py CATALOGUE IDS_LOCK [--check]

CATALOGUE is the SDK's catalogue/rac1/classes.json (the behaviour catalogue: each class's update
function and the hook point it is); IDS_LOCK is OpenRAC's sdk/bindings/rac1.ids.lock, which gives
each hook point's permanent id for its aliases (the catalogue names the hook points by alias). For
each class of classes.tsv the header gives its role and the id of its update's hook point; the
classes the mod times (enemies, roamers, turrets) give the list of update hook points it takes.
--check writes nothing and fails when src/classes.h differs.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ROLES = {"enemy": "DM_ENEMY", "roamer": "DM_ROAMER", "turret": "DM_TURRET", "boss": "DM_BOSS",
         "excluded": "DM_EXCLUDED"}
TIMED = {"enemy", "roamer", "turret"}


def read_table(path: Path) -> list[tuple[int, str, str, str]]:
    rows = []
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cid, role, name, reason = line.split("\t")
        if role not in ROLES:
            raise SystemExit(f"{path.name}: class {cid}: unknown role {role!r}")
        rows.append((int(cid), role, name, reason))
    ids = [r[0] for r in rows]
    if len(ids) != len(set(ids)):
        raise SystemExit(f"{path.name}: a class is listed twice")
    return sorted(rows)


def read_lock(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        hook_id, _anchor, aliases = line.split("\t")
        for alias in aliases.split(","):
            out[alias] = hook_id
    return out


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(catalogue: Path, lock_path: Path) -> str:
    rows = read_table(HERE / "classes.tsv")
    classes = {c["id"]: c for c in json.loads(catalogue.read_text())["classes"]}
    lock = read_lock(lock_path)
    out = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
           "/* Generated by tools/gen_classes.py from classes.tsv and the behaviour catalogue. Do not edit. */",
           "#ifndef DIFFICULTY_CLASSES_H", "#define DIFFICULTY_CLASSES_H", "", "#include <stdint.h>", "",
           "enum { DM_ENEMY, DM_ROAMER, DM_TURRET, DM_BOSS, DM_EXCLUDED };", "",
           "typedef struct dm_class {",
           "    int16_t id;          /* the moby class (oclass, moby +0xA6) */",
           "    uint8_t role;        /* DM_ENEMY, ... (classes.tsv) */",
           "    const char* name;    /* the catalogue's */",
           "    const char* update;  /* its update's hook point, by id; 0 when it has none */",
           "    const char* reason;  /* why it is not an enemy; 0 for one */",
           "} dm_class;", "", "static const dm_class k_dm_classes[] = {"]
    updates = []
    for cid, role, name, reason in rows:
        c = classes.get(cid)
        if c is None:
            raise SystemExit(f"classes.tsv: class {cid} is not in the catalogue")
        hooks = [u for u in c["updates"] if u.get("hook") and u.get("signature") == "void(u32)"]
        update = lock.get(hooks[0]["hook"], hooks[0]["hook"]) if hooks else None
        if role in TIMED and update is None:
            raise SystemExit(f"classes.tsv: class {cid} ({name}) has no update hook point to time")
        if role in TIMED and update not in updates:
            updates.append(update)
        out.append(f"    {{{cid}, {ROLES[role]}, {c_string(name)}, "
                   f"{c_string(update) if update else '0'}, {c_string(reason) if reason != '-' else '0'}}},")
    out += ["};", "", "/* The update hook points of the classes it times (enemies, roamers, turrets). */",
            "static const char* const k_dm_update_hooks[] = {"]
    out += [f"    {c_string(u)}," for u in updates]
    out += ["};", "", "#endif /* DIFFICULTY_CLASSES_H */", ""]
    return "\n".join(out)


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    text = generate(Path(args[0]), Path(args[1]))
    target = HERE / "src" / "classes.h"
    if "--check" in sys.argv:
        if not target.is_file() or target.read_text() != text:
            print(f"stale: {target} (python3 tools/gen_classes.py CATALOGUE IDS_LOCK)", file=sys.stderr)
            return 1
        return 0
    target.write_text(text)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
